/**
 * Map one remote sample-media URL to a catalogue path (relative to MEDIA_DIR),
 * or null when the URL is not sample media this catalogue replaces.
 */
export function localFor(rawUrl) {
  if (/\$\{/.test(rawUrl)) return null; // a template literal: rewrite by hand
  let u;
  try { u = new URL(rawUrl.replace(/&amp;/g, '&')); } catch { return null; }
  const host = u.hostname.replace(/^www\./, '');
  const parts = u.pathname.split('/').filter(Boolean);
  const num = (s) => (/^\d+$/.test(s) ? Number(s) : NaN);

  if (host === 'picsum.photos' || host === 'fastly.picsum.photos') {
    // A video poster should show the first frame of the video it fronts.
    if (parts[0] === 'seed' && parts[1] === 'videoposter') return VIDEO[0].poster;
    if (parts[0] === 'seed' && parts.length >= 4) return photoFor(parts[1], num(parts[2]), num(parts[3]));
    if (parts[0] === 'id' && parts.length >= 4) return photoFor('id' + parts[1], num(parts[2]), num(parts[3]));
    if (parts.length === 2 && !isNaN(num(parts[0]))) return photoFor(u.search || `${parts[0]}x${parts[1]}`, num(parts[0]), num(parts[1]));
    if (parts.length === 1 && !isNaN(num(parts[0]))) return photoFor(u.search || parts[0], 1, 1);
    return null;
  }
  if (host === 'images.unsplash.com') {
    const w = Number(u.searchParams.get('w')) || 1200;
    const h = Number(u.searchParams.get('h')) || (w >= 1600 ? w / 2 : (w * 2) / 3);
    return photoFor(parts.join('/'), w, h);
  }
  if (host === 'i.pravatar.cc') {
    const img = Number(u.searchParams.get('img'));
    const user = u.searchParams.get('u');
    let n = 1;
    if (img) n = ((img - 1) % AVATAR_COUNT) + 1;
    else if (user) n = AVATAR_BY_USER[user] || (hash(user) % AVATAR_COUNT) + 1;
    return avatarFile(n);
  }
  if (host === 'ui-avatars.com') {
    const name = u.searchParams.get('name') || '';
    return avatarFile(AVATAR_BY_USER[name.toLowerCase()] || (hash(name) % AVATAR_COUNT) + 1);
  }
  if (host === 'placehold.co') {
    const m = /^(\d+)x(\d+)$/.exec(parts[0] || '');
    if (!m) return null;
    const [w, h] = [Number(m[1]), Number(m[2])];
    const text = u.searchParams.get('text') || `${w} × ${h}`;
    const file = placeholderFile(w, h, text);
    if (!PLACEHOLDERS.some((p) => p.file === file)) throw new Error(`placehold.co URL with no catalogued placeholder: ${rawUrl}`);
    return file;
  }
  if (host === 'archive.org' && parts[1] === 'nineinchnails_ghosts_I_IV') {
    const track = Number((/^(\d+)_/.exec(parts[2] || '') || [])[1]);
    if (!track) return null;
    return track === 1 ? 'audio/ambient-drift.mp3' : GHOSTS_CYCLE[(track - 2) % GHOSTS_CYCLE.length];
  }
  if (host === 'files.freemusicarchive.org' || host === 'soundhelix.com' || host === 'incompetech.com') {
    return /\.mp3$/i.test(u.pathname) ? 'audio/sunny-arpeggio.mp3' : null;
  }
  if (host === 'w3schools.com') {
    if (/\/horse\.(mp3|ogg)$/.test(u.pathname)) return 'audio/chime.mp3';
    if (/\/mov_bbb\.mp4$/.test(u.pathname)) return 'video/sample-clip.webm';
    if (/\/movie\.mp4$/.test(u.pathname)) return 'video/background-loop.webm';
    return null;
  }
  if (host === 'cdn.pixabay.com' && /\.mp4$/.test(u.pathname)) return 'video/background-loop.webm';
  if (host === 'interactive-examples.mdn.mozilla.net' && /\.mp4$/.test(u.pathname)) return 'video/sample-clip.webm';
  return null;
}
