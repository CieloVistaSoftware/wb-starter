/** Where the stand-ins live, relative to the repo root. */
export const MEDIA_DIR = 'tests/fixtures/offline/media';

function hash(s) {
  let h = 2166136261;
  for (const ch of String(s)) h = Math.imul(h ^ ch.charCodeAt(0), 16777619);
  return h >>> 0;
}

/** The photo family whose aspect ratio is nearest W:H. */
export function familyFor(w, h) {
  const want = Math.log(w / h);
  let best = '3x2', bestD = Infinity;
  for (const [name, f] of Object.entries(PHOTO_FAMILIES)) {
    const d = Math.abs(Math.log(f.w / f.h) - want);
    if (d < bestD) { best = name; bestD = d; }
  }
  return best;
}

/** A photo of roughly W x H, chosen deterministically by `key`. */
export function photoFor(key, w, h) {
  const family = familyFor(w, h);
  return photoFile(family, hash(key) % PHOTO_FAMILIES[family].shots.length);
}

