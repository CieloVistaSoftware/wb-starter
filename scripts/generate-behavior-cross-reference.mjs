#!/usr/bin/env node
/**
 * generate-behavior-cross-reference.mjs -- the inventory in
 * docs/behavior-cross-reference.md (#1099).
 *
 * The doc opened "A complete reference of all WB Behaviors" and had prose for
 * 50 of 185. The prose stays; the claim of completeness moves to a table this
 * script writes between the inventory markers: one row per behavior, read from
 * the registries (tag-map.js and wb-lazy.js, via scripts/lib/behavior-inventory.mjs),
 * so a behavior with no prose is listed as such instead of silently missing.
 *
 *   node scripts/generate-behavior-cross-reference.mjs           # rewrite the table
 *   node scripts/generate-behavior-cross-reference.mjs --check   # exit 1 if it is stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { reachableBehaviors } from './lib/behavior-inventory.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DOC = path.join(ROOT, 'docs', 'behavior-cross-reference.md');
const START = '<!-- inventory:start -- generated by scripts/generate-behavior-cross-reference.mjs; do not edit by hand -->';
const END = '<!-- inventory:end -->';
const BT = String.fromCharCode(96);
const code = (s) => BT + s + BT;

export function buildInventory(doc) {
  const prose = doc.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), '');
  // Section headings name one or more behaviors: "### button", "### article → card",
  // "### x-flex / x-row". Every name in a heading counts.
  const headings = new Set([...prose.matchAll(/^###\s+(.+?)\s*$/gm)]
    .flatMap((m) => m[1].replace(/[`<>]/g, '').toLowerCase().split(/\s*(?:→|\/|,|\s)\s*/))
    .map((t) => t.replace(/\[.*$/, '').trim())
    .filter(Boolean));

  // One row per behavior (the module name), with every way it is written.
  const rows = new Map();
  for (const b of reachableBehaviors(ROOT, { includeLazy: true })) {
    const row = rows.get(b.name) || { name: b.name, tags: new Set(), attrs: new Set() };
    if (b.autoInjected) row.tags.add(b.key); else row.attrs.add('x-' + b.token);
    rows.set(b.name, row);
  }
  const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name));
  let detailed = 0;
  let documented = 0;
  const lines = sorted.map((r) => {
    const docFile = path.join(ROOT, 'docs', 'behaviors', `${r.name}.md`);
    const hasDoc = fs.existsSync(docFile);
    if (hasDoc) documented++;
    // A section may be headed by the behavior, its attribute, or the native tag
    // that injects it (### article documents card).
    const names = [r.name.toLowerCase(), ...[...r.attrs].map((a) => a.toLowerCase()), ...[...r.tags].map((t) => t.toLowerCase())];
    const isDetailed = names.some((n) => headings.has(n) || headings.has(n.replace(/^x-/, '')));
    if (isDetailed) detailed++;
    const written = [...[...r.tags].sort().map((t) => code(`<${t}>`)), ...[...r.attrs].sort().map(code)].join(', ');
    return `| ${code(r.name)} | ${written} | ${hasDoc ? `[behaviors/${r.name}.md](behaviors/${r.name}.md)` : 'undocumented'} | ${isDetailed ? 'yes' : '—'} |`;
  });
  return [
    START,
    '',
    '## Inventory: every behavior',
    '',
    `**${sorted.length} behaviors**, read from ${code('src/core/tag-map.js')} and ${code('src/core/wb-lazy.js')}. ` +
      `${documented} have a reference page in ${code('docs/behaviors/')}; ${detailed} also have a detailed section in this document. ` +
      'A behavior marked "undocumented" exists and works; it has no reference page yet.',
    '',
    '| Behavior | Written as | Reference | Detailed below |',
    '|---|---|---|---|',
    ...lines,
    '',
    END,
  ].join('\n');
}

export function render(doc) {
  const block = buildInventory(doc);
  const re = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);
  if (re.test(doc)) return doc.replace(re, () => block);
  // First run: the inventory goes right after the opening paragraph.
  const at = doc.indexOf('\n---\n');
  return doc.slice(0, at) + '\n\n' + block + '\n' + doc.slice(at);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const raw = fs.readFileSync(DOC, 'utf8');
  const crlf = raw.includes('\r\n');
  const doc = raw.replace(/\r\n/g, '\n');
  const next = render(doc);
  if (process.argv.includes('--check')) {
    if (next !== doc) { console.error('docs/behavior-cross-reference.md inventory is stale: run node scripts/generate-behavior-cross-reference.mjs'); process.exit(1); }
    console.log('inventory up to date');
  } else if (next !== doc) {
    fs.writeFileSync(DOC, crlf ? next.replace(/\n/g, '\r\n') : next);
    console.log('inventory written');
  } else console.log('inventory already up to date');
}
