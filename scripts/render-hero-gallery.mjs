#!/usr/bin/env node
/**
 * render-hero-gallery.mjs -- the playground's 120 card heroes as JPGs with
 * clickable button hotspots (#1597).
 *
 * John: "i love the 120 card hero example, can we make them a jpg with
 * hotspots for the two buttons." The heroes come from
 * demos/lib/hero-permutations.js, the same module the playground's
 * "120 card heroes" example renders, so the gallery always matches it.
 *
 * For each hero this:
 *   1. renders its x-cardhero in demos/test-harness.html at 1200px wide,
 *   2. saves a JPG to images/hero-gallery/hero-NNN.jpg,
 *   3. measures its CTA buttons, in image pixels, as the hotspots.
 * Then it rewrites the generated block of pages/hero-gallery.html: one figure
 * per hero, an <img> plus an SVG overlay whose <a> rects link to that hero's
 * own cta-href / cta-secondary-href.
 *
 * Usage:
 *   node scripts/render-hero-gallery.mjs           render all 120, rewrite the page
 *   node scripts/render-hero-gallery.mjs --check   exit 1 if the page block is not
 *                                                  what the module would produce
 *                                                  (hotspots are read from the page)
 *
 * It starts its own server.js on a free port, and uses Playwright's Chromium.
 */
import { spawn } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import net from 'node:net';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { heroPermutations } from '../demos/lib/hero-permutations.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PAGE = path.join(ROOT, 'pages', 'hero-gallery.html');
const IMG_DIR = path.join(ROOT, 'images', 'hero-gallery');
const WIDTH = 1200;
const JPG_QUALITY = 72;
const START = '<!-- hero-gallery:start -- generated by scripts/render-hero-gallery.mjs; do not edit by hand -->';
const END = '<!-- hero-gallery:end -->';

const pad = (n) => String(n).padStart(3, '0');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** The page block for the measured heroes. Pure: the same input gives the same text. */
export function galleryBlock(rows) {
  const items = rows.map((r) => {
    const n = pad(r.index);
    const links = r.hotspots.map((h) =>
      `        <a href="${esc(h.href)}" aria-label="${esc(h.label)} (hero #${r.index})"><rect class="hg-hotspot" x="${h.x}" y="${h.y}" width="${h.w}" height="${h.h}" rx="8"></rect></a>`,
    ).join('\n');
    return [
      `  <li id="herogallery-item-${n}" class="hg-item">`,
      `    <figure id="herogallery-figure-${n}" class="hg-figure">`,
      `      <div id="herogallery-frame-${n}" class="hg-frame">`,
      `      <img id="herogallery-img-${n}" class="hg-img" src="images/hero-gallery/hero-${n}.jpg" width="${r.width}" height="${r.height}" loading="lazy" alt="Hero #${r.index}: ${esc(r.title)}">`,
      `      <svg id="herogallery-hotspots-${n}" class="hg-hotspots" viewBox="0 0 ${r.width} ${r.height}" preserveAspectRatio="none" aria-label="Buttons on hero #${r.index}">`,
      links,
      `      </svg>`,
      `      </div>`,
      `      <figcaption id="herogallery-caption-${n}" class="hg-caption">#${r.index} · ${esc(r.title)}</figcaption>`,
      `    </figure>`,
      `  </li>`,
    ].filter((l) => l !== '').join('\n');
  });
  return `${START}\n<ul id="herogallery-list" class="hg-list">\n${items.join('\n')}\n</ul>\n${END}`;
}

function replaceBlock(page, block) {
  const a = page.indexOf(START);
  const b = page.indexOf(END);
  if (a < 0 || b < a) throw new Error(`pages/hero-gallery.html has no ${START} ... ${END} block`);
  return page.slice(0, a) + block + page.slice(b + END.length);
}

/** Hotspots as the page currently has them, so --check needs no browser. */
function readPageRows(page) {
  const rows = [];
  for (const m of page.matchAll(/<li id="herogallery-item-(\d+)"[\s\S]*?<\/li>/g)) {
    const li = m[0];
    const img = li.match(/width="(\d+)" height="(\d+)"/);
    const hotspots = [...li.matchAll(/<a href="([^"]*)" aria-label="([^"]*) \(hero #\d+\)"><rect class="hg-hotspot" x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"/g)]
      .map((h) => ({ href: h[1].replace(/&amp;/g, '&'), label: h[2].replace(/&amp;/g, '&'), x: +h[3], y: +h[4], w: +h[5], h: +h[6] }));
    rows.push({ index: Number(m[1]), width: +img[1], height: +img[2], hotspots });
  }
  return rows;
}

/** Width and height from a JPEG's SOF marker. */
function jpegSize(buf) {
  for (let i = 2; i < buf.length; ) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1];
    if (marker >= 0xc0 && marker <= 0xc3) return { height: buf.readUInt16BE(i + 5), width: buf.readUInt16BE(i + 7) };
    i += 2 + buf.readUInt16BE(i + 2);
  }
  throw new Error('no SOF marker in the screenshot');
}

function freePort() {
  return new Promise((resolve) => {
    const s = net.createServer().listen(0, () => { const p = s.address().port; s.close(() => resolve(p)); });
  });
}

async function render(heroes) {
  const { chromium } = await import('playwright');
  const port = await freePort();
  const server = spawn(process.execPath, ['server.js'], {
    cwd: ROOT, env: { ...process.env, PORT: String(port), WB_NO_OPEN: '1', CI: '1' }, stdio: 'ignore',
  });
  try {
    const base = `http://localhost:${port}`;
    for (let t = Date.now(); ; ) {
      try { if ((await fetch(base + '/')).ok) break; } catch { /* not up yet */ }
      if (Date.now() - t > 30_000) throw new Error('server.js did not start');
      await new Promise((r) => setTimeout(r, 300));
    }
    const launch = process.env.WB_CHROMIUM ? { executablePath: process.env.WB_CHROMIUM } : {};
    const browser = await chromium.launch(launch);
    const page = await browser.newPage({ viewport: { width: WIDTH + 64, height: 900 }, deviceScaleFactor: 1 });
    await page.goto(base + '/demos/test-harness.html');
    await page.waitForFunction(() => window.WB?.behaviors, null, { timeout: 20_000 });
    // Every hero shown in its final state. The CTA buttons slide up on entry,
    // so measuring them mid-animation put the hotspots 16px below the buttons
    // in the (animations-disabled) screenshot.
    await page.addStyleTag({ content: '*, *::before, *::after { animation-duration: 0s !important; animation-delay: 0s !important; transition: none !important; }' });
    mkdirSync(IMG_DIR, { recursive: true });

    const rows = [];
    for (const h of heroes) {
      // x-fadein is the playground's entrance animation, not part of the hero:
      // a still image of it mid-fade would be half transparent.
      const markup = h.heroMarkup.replace(/\n\s*x-fadein(?=[\s>])/, '');
      const box = await page.evaluate(async ({ markup, width }) => {
        document.querySelectorAll('.hg-render').forEach((n) => n.remove());
        const host = document.createElement('div');
        host.className = 'hg-render';
        host.style.width = width + 'px';
        host.innerHTML = markup;
        document.body.appendChild(host);
        await window.WB.scan(host, { eager: true });
        await window.WB.whenIdle({ timeout: 10_000 });
        const hero = host.firstElementChild;
        await Promise.all([...hero.querySelectorAll('img')].map((img) => img.decode().catch(() => {})));
        await document.fonts.ready;
        const r = hero.getBoundingClientRect();
        const ctas = [...hero.querySelectorAll('a.x-hero-cta')].map((a) => {
          const b = a.getBoundingClientRect();
          return { label: a.textContent.trim(), href: a.getAttribute('href'), x: b.left - r.left, y: b.top - r.top, w: b.width, h: b.height };
        });
        return { ctas };
      }, { markup, width: WIDTH });

      const file = path.join(IMG_DIR, `hero-${pad(h.index)}.jpg`);
      const jpg = await page.locator('.hg-render > *').first().screenshot({ path: file, type: 'jpeg', quality: JPG_QUALITY, animations: 'disabled' });
      // The image's own size, not the hero's rounded box: a 455.4px hero is
      // a 456px screenshot, and the page's viewBox must match the pixels.
      const size = jpegSize(jpg);

      const expected = [h.cta, h.cta2].filter(Boolean);
      if (box.ctas.length !== expected.length) {
        throw new Error(`hero #${h.index}: rendered ${box.ctas.length} buttons, the module defines ${expected.length}`);
      }
      rows.push({
        index: h.index, title: h.title, width: size.width, height: size.height,
        // The link is the module's, not whatever the DOM ended up with: the
        // gallery promises each hero's own cta-href.
        hotspots: box.ctas.map((c, k) => ({
          label: expected[k].label, href: expected[k].href,
          x: Math.round(c.x), y: Math.round(c.y), w: Math.round(c.w), h: Math.round(c.h),
        })),
      });
      process.stdout.write(`\r  rendered ${h.index}/${heroes.length}`);
    }
    process.stdout.write('\n');
    await browser.close();
    return rows;
  } finally {
    server.kill();
  }
}

async function main() {
  const heroes = heroPermutations();
  const page = readFileSync(PAGE, 'utf8');

  if (process.argv.includes('--check')) {
    // Titles, links and labels come from the module; positions from the page.
    const onPage = readPageRows(page);
    const rows = heroes.map((h, k) => {
      const p = onPage[k];
      if (!p) return null;
      const expected = [h.cta, h.cta2].filter(Boolean);
      return {
        index: h.index, title: h.title, width: p.width, height: p.height,
        hotspots: expected.map((e, j) => ({ ...p.hotspots[j], label: e.label, href: e.href })),
      };
    });
    if (rows.includes(null) || replaceBlock(page, galleryBlock(rows)) !== page) {
      console.error('pages/hero-gallery.html is out of date with demos/lib/hero-permutations.js.');
      console.error('Run: node scripts/render-hero-gallery.mjs');
      process.exit(1);
    }
    console.log(`hero gallery: ${heroes.length} heroes match the playground module`);
    return;
  }

  const rows = await render(heroes);
  writeFileSync(PAGE, replaceBlock(page, galleryBlock(rows)));
  console.log(`wrote ${rows.length} JPGs to images/hero-gallery/ and updated pages/hero-gallery.html`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => { console.error(err); process.exit(1); });
}
