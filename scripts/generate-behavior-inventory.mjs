#!/usr/bin/env node
/**
 * generate-behavior-inventory.mjs -- the behavior list in
 * docs/behavior-cross-reference.md, generated from the code (#1099).
 *
 * The cross-reference opened "A complete reference of all WB Behaviors" and
 * covered 50 of 185. Every list of behaviors that a person types goes short
 * the same way (#764, #1098), so the LIST is generated and the prose stays
 * hand-written:
 *
 *   - every x- attribute in tag-map.js's extensionMap and wb-lazy.js's
 *     WB_LAZY_ONLY_ATTRIBUTES (the union pages/behaviors.html reads, #1056);
 *   - every semantic selector in tag-map.js's nativeMap;
 *   - each row names the prose section that documents it, or says
 *     "undocumented" -- a gap someone can see and fill, not an omission.
 *
 * The rows are written between the two INVENTORY markers in the doc. Nothing
 * outside the markers is touched.
 *
 * Usage:
 *   node scripts/generate-behavior-inventory.mjs           # rewrite the block
 *   node scripts/generate-behavior-inventory.mjs --check   # exit 1 if stale
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = 'docs/behavior-cross-reference.md';
export const START = '<!-- INVENTORY:START (generated by scripts/generate-behavior-inventory.mjs -- do not edit by hand) -->';
export const END = '<!-- INVENTORY:END -->';

/** The registries, as [name, behavior] rows. */
export async function loadRegistries() {
  const tag = await import(pathToFileURL(join(ROOT, 'src/core/tag-map.js')).href);
  const lazy = await import(pathToFileURL(join(ROOT, 'src/core/wb-lazy.js')).href);
  const attrs = { ...(lazy.WB_LAZY_ONLY_ATTRIBUTES || {}), ...tag.extensionMap };
  return {
    attributes: Object.entries(attrs).sort(([a], [b]) => a.localeCompare(b)),
    semantic: Object.entries(tag.nativeMap),
  };
}

/** `### x-flex / x-row` -> ['x-flex', 'x-row']; `### article → card` -> ['article']. */
function headingNames(heading) {
  return heading.split(/\s*\/\s*/).map((part) => part.split(/\s*→\s*/)[0].trim());
}

/** Map a name (`x-grid`, `article`, `input[type="radio"]`) to the prose heading that documents it. */
function sectionIndex(doc) {
  const outside = doc.replace(new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`), '');
  const index = new Map();
  for (const m of outside.matchAll(/^### (.+)$/gm)) {
    const heading = m[1].trim();
    for (const name of headingNames(heading)) if (!index.has(name)) index.set(name, heading);
  }
  return index;
}

function escape(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

const cell = (s) => String(s).replace(/\|/g, '\\|');

/** The generated block, markers included. Pure: same inputs, same text. */
export function renderInventory(doc, { attributes, semantic }) {
  const sections = sectionIndex(doc);
  const where = (...names) => {
    for (const n of names) if (sections.has(n)) return `§ ${sections.get(n)}`;
    return '*undocumented*';
  };

  const attrRows = attributes.map(([attr, behavior]) =>
    `| \`${cell(attr)}\` | \`${cell(behavior)}\` | ${cell(where(attr, behavior))} |`);
  const semRows = semantic.map(([selector, behavior]) => {
    const tagName = selector.replace(/\[.*$/, '');
    return `| \`${cell(selector)}\` | \`${cell(behavior)}\` | ${cell(where(selector, behavior, tagName))} |`;
  });
  const documented = [...attrRows, ...semRows].filter((r) => !r.endsWith('*undocumented* |')).length;
  const total = attrRows.length + semRows.length;

  return [
    START,
    '',
    `**${total} entries:** ${attributes.length} x- attributes and ${semantic.length} semantic selectors. ` +
      `${documented} have a prose section in this document; the rest are marked *undocumented*.`,
    '',
    '### x- attributes',
    '',
    '| Attribute | Behavior | Documented in |',
    '|---|---|---|',
    ...attrRows,
    '',
    '### Semantic elements (auto-injected)',
    '',
    '| Selector | Behavior | Documented in |',
    '|---|---|---|',
    ...semRows,
    '',
    END,
  ].join('\n');
}

/** The doc with its block replaced by a freshly rendered one. */
export function withInventory(doc, registries) {
  const block = renderInventory(doc, registries);
  const re = new RegExp(`${escape(START)}[\\s\\S]*?${escape(END)}`);
  if (!re.test(doc)) throw new Error(`${DOC} has no ${START.slice(0, 22)}… marker pair`);
  return doc.replace(re, () => block);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const path = join(ROOT, DOC);
  const doc = readFileSync(path, 'utf8');
  const next = withInventory(doc, await loadRegistries());
  if (process.argv.includes('--check')) {
    if (next !== doc) {
      console.error(`${DOC}: the behavior inventory is out of date. Run: node scripts/generate-behavior-inventory.mjs`);
      process.exit(1);
    }
    console.log(`${DOC}: behavior inventory is current.`);
  } else if (next !== doc) {
    writeFileSync(path, next, 'utf8');
    console.log(`${DOC}: behavior inventory written.`);
  } else {
    console.log(`${DOC}: behavior inventory already current.`);
  }
}
