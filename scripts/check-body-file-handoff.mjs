#!/usr/bin/env node
/**
 * Claude Code PreToolUse hook (Bash): refuse to publish a body file whose
 * bytes changed since this writer wrote them (#1336).
 *
 * The one thing that made the 2026-10-03 swap possible is that
 * `git commit -F commit-msg.txt` is perfectly happy with a valid file. It has
 * no way to know the prose in it is about another agent's issue. Neither does
 * `gh pr create --body-file` or `gh issue comment --body-file`, and those
 * publish on the spot.
 *
 * So the check is: the file is hashed when it is written
 * (scripts/record-body-file-write.mjs) and hashed again here, in the instant
 * before git or gh reads it. Same bytes, nothing happens. Different bytes,
 * exit 2 -- Claude Code blocks the command and shows this text to the agent,
 * which is the loud failure the incident did not have.
 *
 * It catches the collision regardless of the filename, so it does not depend
 * on anyone remembering a naming convention, and it catches an overwrite by
 * any mechanism (another agent's Write, a heredoc, an editor) because it
 * compares the bytes rather than trusting a record of the overwrite.
 *
 * It is the pre-publication half of #1336. The commit-msg hook, the PR-body
 * workflow and the closing-comment workflow judge text that is already
 * written or already published, and only by its issue number; this judges the
 * file itself, before git or gh reads it. See scripts/lib/body-file.mjs.
 *
 * Fails OPEN, deliberately, in exactly one case: a path this writer never
 * wrote with a tool has no record to compare, so it passes. A guard that
 * blocked every file it has never seen would block `git commit -F` on a file
 * generated by a script, and would be turned off.
 */
import { readFileSync } from 'node:fs';
import { verifyBodyFile, bodyFilePaths, writerKey, resolveFrom } from './lib/body-file.mjs';

let payload = {};
try { payload = JSON.parse(readFileSync(0, 'utf8') || '{}'); } catch { process.exit(0); }

const command = (payload.tool_input && payload.tool_input.command) || '';
const paths = bodyFilePaths(command);
if (!paths.length) process.exit(0);

const cwd = payload.cwd || process.cwd();
const writer = writerKey({ sessionId: payload.session_id, cwd });

const problems = [];
for (const raw of paths) {
  const file = resolveFrom(cwd, raw);
  const v = verifyBodyFile(file, writer);
  if (v.status === 'unchanged' || v.status === 'unrecorded') continue;

  if (v.status === 'missing') {
    problems.push(
      `${raw}\n`
      + '    is gone or unreadable, but this command is about to publish it.\n'
      + `    You wrote it at ${v.mine.at}, starting: ${v.mine.firstLine || '(empty)'}`,
    );
    continue;
  }

  const culprit = v.culprit
    ? `\n    Those are the bytes another writer (${v.culprit.writer}) put there at ${v.culprit.at}.`
    : '\n    Something other than this writer wrote over it.';
  problems.push(
    `${raw}\n`
    + `    You wrote, at ${v.mine.at}:\n      ${v.mine.firstLine || '(empty)'}\n`
    + `    On disk right now:\n      ${firstLineNow(file)}${culprit}`,
  );
}

function firstLineNow(file) {
  try {
    const text = readFileSync(file, 'utf8');
    return (text.split(/\r?\n/).find((l) => l.trim()) || '(empty)').trim().slice(0, 120);
  } catch { return '(unreadable)'; }
}

if (!problems.length) process.exit(0);

process.stderr.write(
  'BLOCKED (#1336): a body file this command publishes is not the file you wrote.\n\n'
  + `  ${problems.join('\n\n  ')}\n\n`
  + 'This is the shared-scratchpad collision: parallel agents share one scratchpad\n'
  + 'directory, and a second agent writing the same obvious name silently replaced\n'
  + 'your content. Publishing it now would describe another agent\'s work.\n\n'
  + 'Rewrite the file under a name that cannot collide -- include the issue number,\n'
  + 'e.g. commit-msg-1336.txt -- then run the command again.\n',
);
process.exit(2);
