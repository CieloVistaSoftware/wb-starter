/**
 * FIX DATA INTEGRITY
 * ==================
 * data/fixes.json is the Fix Viewer's table on the live site (#1861).
 *
 * John, 2026-10-13: "our fix viewer has not been maintained at all". The site
 * is static, so /api/fixes is a 404 there and the viewer read this file: 13
 * hand-written rows from 2026-02-16 that nothing ever updated. It is now the
 * table traced from git (scripts/lib/fixes.mjs), written by the stamp workflow
 * after every push to main. These tests fail if it goes back to being written
 * by hand, or if the workflow stops writing it.
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { test, expect } from '../fixtures/offline';
import { readJson, DATA_FILES, ROOT } from '../base';

const data = readJson<any>(DATA_FILES.fixes);

test.describe('Fix Data Integrity', () => {
  test('data/fixes.json is the table traced from git, not a hand-written list', () => {
    expect(data, 'data/fixes.json should be parseable').toBeTruthy();
    expect(data.fixes, 'the hand-written `fixes` list is back; the file is generated by scripts/generate-fixes.mjs').toBeUndefined();
    expect(Array.isArray(data.rows) && data.rows.length, 'data/fixes.json has no traced rows').toBeTruthy();
    expect(data.counts.traced).toBe(data.rows.length);
  });

  test('every row names its issue, its state and the commits that fixed it', () => {
    const bad = data.rows.filter((r: any) => !Number.isInteger(r.number)
      || !['open', 'closed'].includes(r.state)
      || !Array.isArray(r.commits) || !r.commits.length
      || r.commits.some((c: any) => !/^[0-9a-f]{7,40}$/.test(c.sha))
      || !Array.isArray(r.files) || r.files.some((f: any) => !f.path || !f.sha));
    expect(bad.map((r: any) => r.number), 'rows missing their issue, state, commits or files').toEqual([]);
  });

  test('it was built from this branch\'s history', () => {
    // A table built from a commit this branch does not contain describes some
    // other history.
    const sha = data.builtFrom?.sha;
    expect(sha, 'data/fixes.json does not say which commit it describes').toMatch(/^[0-9a-f]{40}$/);
    let isAncestor = true;
    try {
      execFileSync('git', ['merge-base', '--is-ancestor', sha, 'HEAD'], { cwd: ROOT, stdio: 'ignore' });
    } catch (err: any) {
      // Exit 1 is "not an ancestor"; anything else (a shallow clone without
      // that commit) cannot answer, and is not this file's fault.
      if (err.status === 1) isAncestor = false;
    }
    expect(isAncestor, `data/fixes.json was built from ${sha}, which is not in this branch's history`).toBe(true);
  });

  test('the stamp workflow regenerates it on every push to main', () => {
    const workflow = fs.readFileSync(path.join(ROOT, '.github', 'workflows', 'stamp-version-on-main.yml'), 'utf8');
    const fixes = workflow.indexOf('node scripts/generate-fixes.mjs');
    expect(fixes, 'stamp-version-on-main.yml no longer runs scripts/generate-fixes.mjs').toBeGreaterThan(-1);
    // Releases are read from data/releases.json, so it must be written first.
    expect(fixes, 'generate-fixes.mjs must run after release-versions.mjs')
      .toBeGreaterThan(workflow.indexOf('node scripts/release-versions.mjs'));
  });
});
